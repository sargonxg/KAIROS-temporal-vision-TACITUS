function renderRelationMatrix(data) {
  const counts = data.diagnostics?.relation_counts || {};
  const entries = Object.entries(counts).sort((a, b) => b[1] - a[1]).slice(0, 10);
  const max = Math.max(1, ...entries.map(([, value]) => value));
  $('relation-matrix').innerHTML = entries.map(([label, value]) => `
    <div class="matrix-row">
      <span>${escapeHtml(humanRel(label))}</span>
      <div class="matrix-bar" title="${escapeHtml(label)}: ${value}">
        <i style="width:${Math.max(4, (value / max) * 100)}%"></i>
      </div>
    </div>
  `).join('') || '<div class="text-sm text-zinc-500">No relation counts yet.</div>';
}

