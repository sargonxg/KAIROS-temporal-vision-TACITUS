async function analyze() {
  const text = $('text-input').value.trim();
  if (!text) return;

  const btn = $('btn-analyze');
  btn.disabled = true;
  btn.classList.add('opacity-50');
  setStatus('Analyzing temporal structure...', 'text-amber-300');

  try {
    const geminiKey = $('gemini-key').value.trim();
    const geminiModel = $('gemini-model').value.trim();
    const body = { text, analysis_mode: text.length > 4500 ? 'dossier' : 'auto' };
    if (geminiKey) {
      body.gemini_api_key = geminiKey;
      if (geminiModel) body.gemini_model = geminiModel;
    }
    const res = await fetch('/api/analyze', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(body),
    });
    const payload = await res.json();
    if (!res.ok) throw new Error(payload.error || `HTTP ${res.status}`);
    render(payload, text);
    setStatus(`Done: ${payload.dates.length} dates, ${payload.events.length} events, ${payload.frictions.length} frictions, ${payload.relations.length} relations.`, 'text-emerald-300');
  } catch (err) {
    console.error(err);
    setStatus(`Error: ${err.message}`, 'text-red-300');
  } finally {
    btn.disabled = false;
    btn.classList.remove('opacity-50');
  }
}

