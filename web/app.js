function summarizeSignal(data) {
  const lines = [];
  for (const ep of data.episodes || []) {
    const start = shortDate(ep.interval?.from);
    const end = ep.interval?.to ? shortDate(ep.interval.to) : 'open';
    lines.push(`${String(ep.kind || 'custom').padEnd(12)} ${start} -> ${end} :: ${ep.title}`);
  }
  return lines.join('\n') || 'no episodes detected';
}

function renderTimeline(data) {
  const palette = {
    regime: '#ef4444',
    leadership: '#38bdf8',
    agreement: '#22c55e',
    sanction: '#a78bfa',
    escalation: '#f97316',
    de_escalation: '#14b8a6',
    pivot: '#facc15',
    crisis: '#fb7185',
    custom: '#94a3b8',
  };
  const groupOrder = ['crisis', 'agreement', 'sanction', 'leadership', 'escalation', 'pivot', 'custom'];
  const groups = groupOrder.map((kind) => ({ id: kind, content: kindLabel(kind) }));
  const items = (data.episodes || []).map((ep) => {
    const kind = ep.kind || 'custom';
    return {
      id: ep.id,
      group: groupOrder.includes(kind) ? kind : 'custom',
      content: `<strong>${escapeHtml(ep.title)}</strong><em>${escapeHtml(kindLabel(kind))}</em>`,
      start: ep.interval?.from,
      end: ep.interval?.to || new Date().toISOString(),
      style: `background:${palette[kind] || '#94a3b8'};color:#071014;border:0;padding:6px 8px;font-weight:800;`,
      title: ep.narrative || '',
    };
  });
  const container = $('timeline');
  container.innerHTML = '';
  if (!items.length || !window.vis) {
    container.textContent = items.length ? 'Timeline library failed to load.' : 'No episodes detected.';
    return;
  }
  new vis.Timeline(container, new vis.DataSet(items), new vis.DataSet(groups), {
    stack: true,
    margin: { item: 14, axis: 12 },
    orientation: 'top',
    zoomable: true,
    moveable: true,
    height: 360,
    groupOrder: (a, b) => groupOrder.indexOf(a.id) - groupOrder.indexOf(b.id),
    tooltip: { followMouse: true },
  });
}

